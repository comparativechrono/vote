# Every figure quoted in js/deck-trains.js, from the trains data. Run from the repository: Rscript dev/trains-check.R
trains <- read.csv("data/trains.csv", stringsAsFactors = TRUE)
str(trains)
summary(trains$delay)
mean(trains$delay == 0); mean(trains$delay <= 2); mean(trains$late)
table(trains$origin)
t.test(delay ~ peak, data = trains)
wilcox.test(delay ~ peak, data = trains)
tab <- table(trains$rain, trains$late); print(tab)
chisq.test(tab)
chisq.test(tab)$expected
fisher.test(tab)
prop.table(tab, 1)
fit <- aov(delay ~ origin, data = trains); print(summary(fit))
print(TukeyHSD(fit))
kruskal.test(delay ~ origin, data = trains)
tapply(trains$delay, trains$origin, mean)
tapply(trains$stops, trains$origin, mean)
summary(lm(delay ~ stops, data = trains))
summary(lm(delay ~ stops + origin, data = trains))
kruskal.test(delay ~ day, data = trains)
summary(aov(delay ~ day, data = trains))
tapply(trains$delay, trains$day, mean)
t.test(delay ~ day == "Mon", data = trains)
tapply(trains$delay, trains$peak, mean)
